#!/usr/bin/env python3
"""Regenerate shared/asxlib/runtime_lock.py from PyPI (maintainer tool, needs network).

The lock pins one Pillow release and the SHA-256 of every wheel for the supported
platforms. ``asynx.py runtime prepare`` installs only from these hashes.

    python3 -S src/lock_runtime.py [--version 12.3.0]
"""

from __future__ import annotations

import argparse
import json
import re
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = REPO_ROOT / "shared" / "asxlib" / "runtime_lock.py"
DEFAULT_VERSION = "12.3.0"
PYTHONS = ("310", "311", "312", "313", "314")
PLATFORM_PATTERNS = (
    r"macosx_\d+_\d+_(arm64|x86_64)",
    r"manylinux_2_\d+_(x86_64|aarch64)",
    r"musllinux_1_\d+_(x86_64|aarch64)",
    r"win_(amd64|arm64)",
)


def supported(filename: str) -> bool:
    parts = filename[: -len(".whl")].split("-")
    python_tag, abi_tag, platform_tags = parts[-3], parts[-2], parts[-1]
    if python_tag not in {f"cp{v}" for v in PYTHONS} or abi_tag != python_tag:
        return False
    return any(
        re.fullmatch(pattern, tag) for tag in platform_tags.split(".") for pattern in PLATFORM_PATTERNS
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", default=DEFAULT_VERSION)
    args = parser.parse_args()
    url = f"https://pypi.org/pypi/pillow/{args.version}/json"
    with urllib.request.urlopen(url, timeout=60) as response:  # noqa: S310 - fixed https URL
        release = json.load(response)
    wheels = sorted(
        (
            {"filename": item["filename"], "sha256": item["digests"]["sha256"], "size": item["size"]}
            for item in release["urls"]
            if item["packagetype"] == "bdist_wheel" and supported(item["filename"])
        ),
        key=lambda wheel: wheel["filename"],
    )
    if not wheels:
        raise SystemExit("no supported wheels found")
    lock = {
        "schema": 1,
        "package": "pillow",
        "version": args.version,
        "requirement": f"pillow=={args.version}",
        "license": release["info"].get("license_expression") or release["info"].get("license"),
        "source": f"https://pypi.org/project/pillow/{args.version}/",
        "wheels": wheels,
    }
    body = json.dumps(lock, ensure_ascii=False, indent=4)
    OUTPUT.write_text(
        '"""Generated by src/lock_runtime.py. Do not edit by hand."""\n\n'
        f"LOCK = {body}\n".replace(": null", ": None").replace(": true", ": True").replace(": false", ": False"),
        encoding="utf-8",
    )
    print(f"{OUTPUT}: {len(wheels)} wheels for pillow=={args.version}")


if __name__ == "__main__":
    main()
